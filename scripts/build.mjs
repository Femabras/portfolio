// Attributes are always double-quoted, so an apostrophe needs no escaping.
const esc = (value) =>
  String(value).replace(/[&<>"]/g, (c) => ({ "&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&quot;" })[c]);

// Replaces {tokens}. An unknown token stops the build, so a typo in content/
// cannot reach the page as literal "{token}" text.
function fill(text, vars, where) {
  return String(text).replace(/\{(\w+)\}/g, (match, key) => {
    if (!(key in vars)) throw new Error(`Unknown {${key}} in ${where}: "${text}"`);
    return vars[key];
  });
}

// Dates in content/ are calendar days; read them as UTC so the result does not
// depend on the machine's time zone.
function parseDay(iso) {
  const [y, m, d] = iso.split("-").map(Number);
  return new Date(Date.UTC(y, m - 1, d));
}

function monthYear(t, date, names) {
  return fill(t.monthYear, { month: names[date.getUTCMonth()], year: date.getUTCFullYear() }, "monthYear");
}

const decimal = (t, n) => String(n).replace(".", t.decimal);
const percent = (t, v) => (Array.isArray(v) ? `${decimal(t, v[0])}–${decimal(t, v[1])}%` : `${decimal(t, v)}%`);
const midpoint = (v) => (Array.isArray(v) ? (v[0] + v[1]) / 2 : v);

// Width and height from a PNG or WebP file's header, so the size each page
// declares for an image follows the file when the image is replaced.
function imageSize(file) {
  const buf = readFileSync(path.join(ROOT, file));
  if (buf.toString("latin1", 1, 4) === "PNG") {
    return { width: buf.readUInt32BE(16), height: buf.readUInt32BE(20) };
  }
  if (buf.toString("latin1", 0, 4) === "RIFF" && buf.toString("latin1", 8, 12) === "WEBP") {
    const chunk = buf.toString("latin1", 12, 16);
    if (chunk === "VP8X") return { width: 1 + buf.readUIntLE(24, 3), height: 1 + buf.readUIntLE(27, 3) };
    if (chunk === "VP8 ") return { width: buf.readUInt16LE(26) & 0x3fff, height: buf.readUInt16LE(28) & 0x3fff };
    if (chunk === "VP8L") {
      const bits = buf.readUInt32LE(21);
      return { width: 1 + (bits & 0x3fff), height: 1 + ((bits >>> 14) & 0x3fff) };
    }
  }
  throw new Error(`${file}: cannot read its size (PNG and WebP only)`);
}

// The browser-UI colour each page asks for (<meta name="theme-color">) is its
// background, read from the palette in public/main.css so the two cannot
// drift apart.
const CSS = readFileSync(path.join(ROOT, "public/main.css"), "utf8");
function paletteColour(name) {
  const match = CSS.match(new RegExp(`--${name}:\\s*(\\d+)\\s*,\\s*(\\d+)\\s*,\\s*(\\d+)\\s*;`));
  if (!match) throw new Error(`public/main.css has no --${name} channel list`);
  return `#${match.slice(1, 4).map((c) => Number(c).toString(16).padStart(2, "0")).join("")}`;
}

// Every value a {token} can name, for one language.
function valuesFor(t) {
  const f = site.femabras;
  const firstCommit = parseDay(f.firstCommit);
  const firstRelease = parseDay(f.firstRelease);
  const b = site.backtest;
  return {
    name: site.name,
    email: site.email,
    phone: site.phone.display,
    location: `${site.location.city}, ${site.location.country}`,
    timezone: site.timezone,
    productName: f.name,
    product: site.links.productLabel,
    school: site.education.school,
    gradYear: site.education.year,
    weeksToLaunch: Math.round((firstRelease - firstCommit) / (7 * DAY_MS)),
    releases: f.releases,
    releaseWindowWeeks: f.releaseWindowWeeks,
    adrs: f.adrs,
    languageCount: f.locales.length,
    launchMonth: monthYear(t, firstRelease, t.months),
    startMonth: monthYear(t, firstCommit, t.months),
    startMonthShort: monthYear(t, firstCommit, t.monthsShort),
    year: new Date().getFullYear(),
    leaguePredicted: percent(t, b.leaguePredicted),
    leagueHit: percent(t, b.leagueHit),
    tournamentPredicted: percent(t, b.tournamentPredicted),
    tournamentHit: percent(t, b.tournamentHit),
  };
}

// en.mjs and pt.mjs must have the same keys and list lengths, so the two
// pages always carry the same sections.
function assertSameShape(a, b, where = "content") {
  if (Array.isArray(a) || Array.isArray(b)) {
    if (!Array.isArray(a) || !Array.isArray(b) || a.length !== b.length) {
      throw new Error(`${where}: en.mjs and pt.mjs lists differ in length`);
    }
    a.forEach((item, i) => assertSameShape(item, b[i], `${where}[${i}]`));
    return;
  }
  if (a && typeof a === "object") {
    const ka = Object.keys(a).sort().join(",");
    const kb = Object.keys(b ?? {}).sort().join(",");
    if (ka !== kb) throw new Error(`${where}: en.mjs has {${ka}}, pt.mjs has {${kb}}`);
    for (const key of Object.keys(a)) assertSameShape(a[key], b[key], `${where}.${key}`);
  }
}

