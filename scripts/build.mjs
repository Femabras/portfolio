const outputs = [
  { file: "index.html", html: portfolioPage(en, { root: "./", pub: "./public/", selfHref: "./index.html", otherHref: "./public/portuguese-page.html", url: site.links.site }) },
  { file: "public/portuguese-page.html", html: portfolioPage(pt, { root: "../", pub: "./", selfHref: "./portuguese-page.html", otherHref: "../index.html", url: `${site.links.site}public/portuguese-page.html` }) },
  { file: "resume/resume.html", html: resumePage(), then: `print it to ${site.files.cv} (README.md, "Update the résumé")` },
  { file: "social/og-card.html", html: socialCard(en), then: `capture it to ${site.files.ogImage.en} ${previews}` },
  { file: "social/og-card-pt.html", html: socialCard(pt), then: `capture it to ${site.files.ogImage.pt} ${previews}` },
];

const check = process.argv.includes("--check");
let stale = 0;
const todo = [];
for (const { file, html, then } of outputs) {
  const target = path.join(ROOT, file);
  let current = "";
  try { current = readFileSync(target, "utf8"); } catch { /* a missing page counts as changed */ }
  const changed = current !== html;
  if (check) {
    if (changed) { stale += 1; console.log(`out of date: ${file}`); }
    continue;
  }
  if (changed) {
    mkdirSync(path.dirname(target), { recursive: true });
    writeFileSync(target, html);
    if (then) todo.push(`${file} changed: ${then}.`);
  }
  console.log(`${changed ? "wrote    " : "unchanged"} ${file} (${(Buffer.byteLength(html) / 1024).toFixed(1)} KB)`);
}
if (check) {
  if (stale) {
    console.log("Run `node scripts/build.mjs` and commit the result.");
    process.exit(1);
  }
  console.log("All pages are up to date.");
} else if (todo.length) {
  console.log(["", "Still to do by hand:", ...todo.map((line) => `  ${line}`)].join("\n"));
}
